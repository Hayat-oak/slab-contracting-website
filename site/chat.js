/* SLAB website assistant: a floating chat window that sends the visitor's questions to /api/chat (Claude, answering
   only from the website's content). Follows the page language (html[lang]) and direction. The conversation stays in
   this browser tab (sessionStorage) and is not saved by the website. */
(() => {
  const TEXT = {
    ar: {
      teaser: 'اسأل مساعد سلاب', open: 'فتح المحادثة مع مساعد سلاب', close: 'إغلاق المحادثة', dismiss: 'إخفاء',
      title: 'مساعد سلاب', sub: 'إجابات فورية بالذكاء الاصطناعي',
      welcome: 'مرحبًا بك! أنا المساعد الذكي لسلاب. يمكنني الإجابة عن أسئلتك حول خدماتنا ومراحل العمل ومشاريعنا وكيفية بدء مشروعك.',
      suggest: ['ما الخدمات التي تقدمونها؟', 'ما مراحل تنفيذ المشروع؟', 'في أي مدن تعملون؟', 'كيف أبدأ مشروعي معكم؟'],
      suggestLabel: 'أسئلة مقترحة', placeholder: 'اكتب سؤالك هنا…', send: 'إرسال', typing: 'يكتب…', you: 'أنت', bot: 'مساعد سلاب',
      note: 'الإجابات مولّدة بالذكاء الاصطناعي وقد تحتوي على أخطاء. للتفاصيل الرسمية تواصل مع فريقنا.', start: 'ابدأ مشروعك', restart: 'محادثة جديدة',
      unavailable: 'المساعد غير متاح حاليًا. يمكنك الاتصال بنا على 9200 66197 أو إرسال نموذج «ابدأ مشروعك» وسيتواصل معك فريقنا.',
      busy: 'وصلت إلى الحد المسموح من الرسائل مؤقتًا. حاول مرة أخرى بعد دقائق، أو اتصل بنا على 9200 66197.',
      refused: 'لا أستطيع الإجابة عن هذا السؤال. يسعدني مساعدتك في كل ما يخص سلاب وخدماتها.',
      offline: 'تعذّر الاتصال بالمساعد. تأكد من اتصالك بالإنترنت وحاول مرة أخرى.'
    },
    en: {
      teaser: 'Ask the SLAB assistant', open: 'Open chat with the SLAB assistant', close: 'Close chat', dismiss: 'Dismiss',
      title: 'SLAB Assistant', sub: 'Instant AI answers',
      welcome: 'Welcome! I’m SLAB’s AI assistant. Ask me about our services, delivery stages, projects, or how to start your project.',
      suggest: ['What services do you offer?', 'What are your delivery stages?', 'Which cities do you work in?', 'How do I start a project with you?'],
      suggestLabel: 'Suggested questions', placeholder: 'Type your question…', send: 'Send', typing: 'Typing…', you: 'You', bot: 'SLAB Assistant',
      note: 'Answers are generated by AI and may contain mistakes. For official details, contact our team.', start: 'Start a Project', restart: 'New chat',
      unavailable: 'The assistant is not available right now. Call us on 9200 66197 or send the “Start a Project” form and our team will get back to you.',
      busy: 'You’ve reached the message limit for now. Please try again in a few minutes, or call us on 9200 66197.',
      refused: 'I can’t help with that question. I’m happy to help with anything about SLAB and its services.',
      offline: 'Could not reach the assistant. Check your connection and try again.'
    }
  };
  const STORE = 'slab-chat', TEASER = 'slab-chat-teaser', MAX = 800;
  const ICON = {
    chat: '<svg viewBox="0 0 24 24" aria-hidden="true"><path d="M4 5h16v11H9l-5 4z"/><path d="M8 9.5h8M8 12.5h5"/></svg>',
    close: '<svg viewBox="0 0 24 24" aria-hidden="true"><path d="M6 6l12 12M18 6 6 18"/></svg>',
    send: '<svg viewBox="0 0 24 24" aria-hidden="true"><path d="M4 12h15M13 6l6 6-6 6"/></svg>',
    spark: '<svg viewBox="0 0 24 24" aria-hidden="true"><path d="M12 3v4M12 17v4M3 12h4M17 12h4M6.5 6.5l2.5 2.5M15 15l2.5 2.5M17.5 6.5 15 9M9 15l-2.5 2.5"/></svg>',
    refresh: '<svg viewBox="0 0 24 24" aria-hidden="true"><path d="M20 11a8 8 0 1 0-2.3 5.7M20 5v6h-6"/></svg>',
    mark: '<svg viewBox="0 0 60 44" aria-hidden="true"><path d="M2 14 22 2h36v14L38 24H2z" fill="#adbfca"/><path d="M2 38 22 26h36v10L38 42H2z" fill="#c7d6ca"/></svg>'
  };
  const lang = () => (document.documentElement.lang === 'ar' ? 'ar' : 'en');
  const t = k => TEXT[lang()][k];
  const esc = s => String(s).replace(/[&<>"']/g, c => ({'&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;'}[c]));
  const store = {
    get(k, fallback) { try { const v = sessionStorage.getItem(k); return v ? JSON.parse(v) : fallback; } catch { return fallback; } },
    set(k, v) { try { sessionStorage.setItem(k, JSON.stringify(v)); } catch {} }
  };
  let history = store.get(STORE, []); // [{role: 'user' | 'assistant', content}]
  let busy = false;

  const root = document.createElement('div');
  root.className = 'chat';
  document.body.appendChild(root);

  // Assistant text: paragraphs and "- " lists; phone numbers and emails become links. Everything else is escaped.
  function format(text) {
    const linkify = s => esc(s)
      .replace(/\b(9200\s?66197|920066197)\b/g, '<a href="tel:920066197" dir="ltr">$1</a>')
      .replace(/\b([\w.+-]+@[\w-]+\.[\w.]+)\b/g, '<a href="mailto:$1" dir="ltr">$1</a>');
    const out = [];
    let list = null;
    for (const line of text.split('\n').map(l => l.trim()).filter(Boolean)) {
      const item = line.match(/^(?:[-•*]|\d+[.)])\s+(.*)$/);
      if (item) { (list = list || []).push(`<li>${linkify(item[1])}</li>`); continue; }
      if (list) { out.push(`<ul>${list.join('')}</ul>`); list = null; }
      out.push(`<p>${linkify(line)}</p>`);
    }
    if (list) out.push(`<ul>${list.join('')}</ul>`);
    return out.join('');
  }
  const bubble = (role, html, extra = '') => `<div class="chat-msg is-${role} ${extra}"><span class="visually-hidden">${t(role === 'user' ? 'you' : 'bot')}: </span>${html}</div>`;

  function render() {
    const open = root.classList.contains('is-open');
    const teaserOff = (() => { try { return localStorage.getItem(TEASER) === 'off'; } catch { return false; } })();
    root.innerHTML = `
      <div class="chat-teaser" ${open || teaserOff ? 'hidden' : ''}>
        <button type="button" class="chat-teaser-open" data-chat="open">${ICON.chat}<span>${t('teaser')}</span></button>
        <button type="button" class="chat-teaser-close" data-chat="dismiss" aria-label="${t('dismiss')}">${ICON.close}</button>
      </div>
      <button type="button" class="chat-launcher" data-chat="${open ? 'close' : 'open'}" aria-expanded="${open}" aria-controls="chat-panel" aria-label="${open ? t('close') : t('open')}">${open ? ICON.close : ICON.chat}</button>
      <section class="chat-panel" id="chat-panel" role="dialog" aria-labelledby="chat-title" ${open ? '' : 'hidden'}>
        <header class="chat-head">
          <span class="chat-mark">${ICON.mark}</span>
          <div><h2 id="chat-title">${t('title')}</h2><p>${ICON.spark}${t('sub')}</p></div>
          ${history.length ? `<button type="button" class="chat-icon-btn" data-chat="restart" aria-label="${t('restart')}" title="${t('restart')}">${ICON.refresh}</button>` : ''}
          <button type="button" class="chat-icon-btn" data-chat="close" aria-label="${t('close')}">${ICON.close}</button>
        </header>
        <div class="chat-log" role="log" aria-live="polite" aria-relevant="additions">
          ${bubble('assistant', `<p>${esc(t('welcome'))}</p>`)}
          ${history.map(m => bubble(m.role, m.role === 'user' ? `<p>${esc(m.content)}</p>` : format(m.content), m.error ? 'is-error' : '')).join('')}
          ${busy ? `<div class="chat-msg is-assistant is-typing"><span class="visually-hidden">${t('typing')}</span><i></i><i></i><i></i></div>` : ''}
        </div>
        ${history.length ? '' : `<div class="chat-suggest" role="group" aria-label="${t('suggestLabel')}">${t('suggest').map(q => `<button type="button" data-chat="ask">${esc(q)}</button>`).join('')}</div>`}
        <form class="chat-form" novalidate>
          <label class="visually-hidden" for="chat-input">${t('placeholder')}</label>
          <textarea id="chat-input" rows="1" maxlength="${MAX}" placeholder="${t('placeholder')}" ${busy ? 'disabled' : ''}></textarea>
          <button type="submit" class="chat-send" aria-label="${t('send')}" ${busy ? 'disabled' : ''}>${ICON.send}</button>
        </form>
        <div class="chat-foot"><p>${t('note')}</p><a href="#/contact" data-chat="start">${t('start')}</a></div>
      </section>`;
    const log = root.querySelector('.chat-log');
    if (log) log.scrollTop = log.scrollHeight;
  }

  async function ask(question) {
    const q = question.trim().slice(0, MAX);
    if (!q || busy) return;
    history.push({role: 'user', content: q});
    busy = true; render();
    let reply;
    try {
      const messages = history.filter(m => !m.error).slice(-12).map(({role, content}) => ({role, content}));
      const r = await fetch('/api/chat', {method: 'POST', headers: {'Content-Type': 'application/json'}, body: JSON.stringify({messages})});
      const data = await r.json().catch(() => ({}));
      if (r.ok && data.reply) reply = {role: 'assistant', content: data.reply};
      else if (r.ok && data.refused) reply = {role: 'assistant', content: t('refused'), error: true};
      else reply = {role: 'assistant', content: t(r.status === 429 ? 'busy' : 'unavailable'), error: true};
    } catch {
      reply = {role: 'assistant', content: t(location.protocol === 'file:' ? 'unavailable' : 'offline'), error: true};
    }
    history.push(reply);
    store.set(STORE, history);
    busy = false; render();
    const input = document.getElementById('chat-input');
    if (input) input.focus();
  }

  function setOpen(open) {
    root.classList.toggle('is-open', open);
    render();
    const target = open ? document.getElementById('chat-input') : root.querySelector('.chat-launcher');
    if (target) target.focus();
  }

  root.addEventListener('click', e => {
    const b = e.target.closest('[data-chat]');
    if (!b) return;
    switch (b.dataset.chat) {
      case 'open': setOpen(true); break;
      case 'close': setOpen(false); break;
      case 'dismiss':
        try { localStorage.setItem(TEASER, 'off'); } catch {}
        root.querySelector('.chat-teaser').hidden = true; root.querySelector('.chat-launcher').focus(); break;
      case 'ask': ask(b.textContent); break;
      case 'restart': history = []; store.set(STORE, history); render(); document.getElementById('chat-input').focus(); break;
      case 'start': root.classList.remove('is-open'); render(); break;
    }
  });
  root.addEventListener('submit', e => {
    e.preventDefault();
    const input = document.getElementById('chat-input');
    ask(input.value);
  });
  root.addEventListener('keydown', e => {
    if (e.key === 'Escape' && root.classList.contains('is-open')) { e.preventDefault(); setOpen(false); }
    if (e.key === 'Enter' && !e.shiftKey && e.target.id === 'chat-input' && !e.isComposing) { e.preventDefault(); ask(e.target.value); }
  });
  root.addEventListener('input', e => {
    if (e.target.id !== 'chat-input') return;
    e.target.style.height = 'auto';
    e.target.style.height = Math.min(e.target.scrollHeight, 120) + 'px';
  });
  // Re-label when the visitor switches the site language.
  new MutationObserver(() => { const v = document.getElementById('chat-input'); const draft = v ? v.value : ''; render(); const n = document.getElementById('chat-input'); if (n) n.value = draft; })
    .observe(document.documentElement, {attributes: true, attributeFilter: ['lang']});
  render();
})();
